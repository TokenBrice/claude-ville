#!/usr/bin/env node
// LA-2 (D1): writes `claudeville/src/config/zoneCoordinates.js`, the static
// table that gives each IANA timezone its principal city's latitude and
// longitude, so the village sun follows the system timezone's city with no
// location access.
//
// Sources, all from the system tz database (public domain):
//   zone.tab, zone1970.tab  coordinates, ISO 6709 (+DDMM+DDDMM or seconds)
//   tzdata.zi               "L target alias" links: an alias takes its
//                           target's city (Chrome reports ICU's canonical
//                           names, some of them old aliases: Asia/Calcutta,
//                           Europe/Kiev, America/Buenos_Aires)
// Zones without a city (UTC, Etc/*, CET, EST5EDT) stay out: SolarClock falls
// back to the UTC offset's central meridian at 45 degrees north.
//
// Usage: node scripts/world/build-zone-coordinates.mjs [--zoneinfo=/usr/share/zoneinfo]
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.resolve(HERE, '../../claudeville/src/config/zoneCoordinates.js');
const arg = process.argv.slice(2).find(a => a.startsWith('--zoneinfo='));
const ZONEINFO = arg ? arg.slice('--zoneinfo='.length) : '/usr/share/zoneinfo';

// ISO 6709 sign-degrees-minutes[-seconds], to tenths of a degree.
function parseIso6709(text) {
  const match = /^([+-])(\d{2})(\d{2})(\d{2})?([+-])(\d{3})(\d{2})(\d{2})?$/.exec(text);
  if (!match) throw new Error(`bad coordinates: ${text}`);
  const part = (sign, d, m, s) => (sign === '-' ? -1 : 1) * (Number(d) + Number(m) / 60 + Number(s || 0) / 3600);
  return {
    lat: Math.round(part(match[1], match[2], match[3], match[4]) * 10),
    lon: Math.round(part(match[5], match[6], match[7], match[8]) * 10),
  };
}

const coords = new Map();
for (const file of ['zone.tab', 'zone1970.tab']) {
  for (const line of readFileSync(path.join(ZONEINFO, file), 'utf8').split('\n')) {
    if (!line || line.startsWith('#')) continue;
    const [, at, zone] = line.split('\t');
    coords.set(zone, parseIso6709(at));
  }
}
const zi = readFileSync(path.join(ZONEINFO, 'tzdata.zi'), 'utf8');
const version = /^# version (\S+)/m.exec(zi)?.[1] || 'unknown';
let aliases = 0;
for (const line of zi.split('\n')) {
  const [kind, target, alias] = line.split(' ');
  if (kind !== 'L' || coords.has(alias) || !coords.has(target)) continue;
  coords.set(alias, coords.get(target));
  aliases += 1;
}

// Grouped by area ("Europe" -> "Belgrade 448 205,..."); bare names ("GB",
// "Japan") sit under "".
const groups = new Map();
for (const zone of [...coords.keys()].sort()) {
  const slash = zone.indexOf('/');
  const area = slash < 0 ? '' : zone.slice(0, slash);
  const { lat, lon } = coords.get(zone);
  if (!groups.has(area)) groups.set(area, []);
  groups.get(area).push(`${slash < 0 ? zone : zone.slice(slash + 1)} ${lat} ${lon}`);
}
const body = [...groups].map(([area, list]) => `    ${JSON.stringify(area)}: ${JSON.stringify(list.join(','))},`).join('\n');

writeFileSync(OUT, `// claudeville/src/config/zoneCoordinates.js
//
// GENERATED by scripts/world/build-zone-coordinates.mjs from tzdata ${version}
// (zone.tab and zone1970.tab for coordinates, tzdata.zi for links). The tz
// database is in the public domain. Regenerate rather than edit by hand.
//
// LA-2 (D1): each IANA timezone's principal city as latitude and longitude
// in tenths of a degree (north and east positive), grouped by area. An alias
// (Asia/Calcutta, Europe/Kiev) carries its target's city. ${coords.size} zones,
// ${aliases} of them aliases.

export const ZONE_TABLE_SOURCE = 'tzdata ${version}';

const ZONES = Object.freeze({
${body}
});

let table = null;

/** The zone's city as { lat, lon } in degrees, or null for a zone with no city. */
export function zoneCoordinates(zone) {
    if (!table) {
        table = new Map();
        for (const [area, list] of Object.entries(ZONES)) {
            for (const entry of list.split(',')) {
                const [name, lat, lon] = entry.split(' ');
                table.set(area ? \`\${area}/\${name}\` : name, Object.freeze({ lat: Number(lat) / 10, lon: Number(lon) / 10 }));
            }
        }
    }
    return table.get(String(zone || '')) || null;
}
`);
console.log(`wrote ${path.relative(process.cwd(), OUT)}: ${coords.size} zones (${aliases} aliases), tzdata ${version}`);
