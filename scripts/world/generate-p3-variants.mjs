#!/usr/bin/env node
// 10.3 — writes claudeville/src/config/p3Variants.js: the Display P3 variant
// of every reserved status and C4 effect hue (DisplayColor P3_RESERVED_HUES),
// computed by DisplayColor's own role mapping (`p3RoleInk`: OKLab chroma
// ×P3_ROLE_CHROMA at the same lightness and hue, bisected into the P3
// gamut), so an overlay or Canvas ink and the GPU role/mark path give a
// reserved hue the same P3 colour.
//
//   node scripts/world/generate-p3-variants.mjs           # write
//   node scripts/world/generate-p3-variants.mjs --check   # exit 1 when stale
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const target = resolve(root, 'claudeville/src/config/p3Variants.js');
const { P3_RESERVED_HUES, p3RoleInk } = await import(resolve(root, 'claudeville/src/presentation/character-mode/DisplayColor.js'));

const body = P3_RESERVED_HUES.map(hex => `    '${hex}': '${p3RoleInk(hex)}',`).join('\n');
const expected = `// GENERATED by scripts/world/generate-p3-variants.mjs — do not edit by hand.
// 10.3: the Display P3 variant of each reserved status and C4 effect hue
// (DisplayColor P3_RESERVED_HUES through p3RoleInk, the shaders' role chroma),
// drawn on the overlay only while its 2D context is display-p3 and the window
// is on a P3 screen (DisplayColor installP3OverlayInks). Keys are lowercase
// sRGB hex.
export const P3_VARIANTS = Object.freeze({
${body}
});
`;

if (process.argv.includes('--check')) {
    const actual = existsSync(target) ? readFileSync(target, 'utf8') : null;
    if (actual !== expected) {
        console.error(`${relative(root, target)} is stale: run node scripts/world/generate-p3-variants.mjs`);
        process.exitCode = 1;
    }
} else {
    writeFileSync(target, expected);
    console.log(`wrote ${relative(root, target)} (${P3_RESERVED_HUES.length} variants)`);
}
